# TURN PROMPT BUILDER
# ────────────────────────────────────────────────────────────────

def build_turn_prompt(canvas_json: str, turn_number: int) -> str:
    urgency = ""
    if turn_number >= 8:
        urgency = "【已进行 8 轮以上】必须结晶，即使信息不完整也输出当前最佳版本，在 ai_reservations 中注明不确定之处。"
    elif turn_number >= 6:
        urgency = f"【第 {turn_number} 轮】如果结晶条件已满足，立即结晶，不要再问新问题。"

    return f"""---
{urgency}
当前画布状态：
{canvas_json}

回复前做四个判断：
1. 这轮我能给用户什么新的信息、判断或视角？（先想这个，再想问什么）
2. 四个关键信息（锚点观察/核心假设/决策背景/硬约束）还缺哪个？优先用讨论方式自然带出，而不是直接问。
3. 用户是否连续两轮无法提供有效信息？如果是，立即切换到主动给候选方向模式。
4. clarity_score ≥ 6 且结晶条件满足？如果是，直接结晶。

原则：每轮 reply 里，你提供的信息量 ≥ 你提出的问题数量。
每轮最多问一个问题，且必须基于用户上一轮说的具体内容延伸。

回复必须是且只能是合法 JSON，不加任何额外文字。
---"""


